process.env.EXPO_ROUTER_APP_ROOT = './app';
process.env.EXPO_ROUTER_IMPORT_MODE = 'sync';

const { spawnSync } = require('node:child_process');
const path = require('node:path');
const { getDefaultConfig } = require('expo/metro-config');
const { withUniwindConfig } = require('uniwind/metro');

const projectRoot = __dirname;
const config = getDefaultConfig(projectRoot);

// ── Block list ───────────────────────────────────────────────────────────────
// Never crawl/watch native build output, reports or VCS internals.
// Split on separators FIRST, then escape each segment and re-join with a
// `[\\/]` class, so the pattern matches whichever separator Metro reports.
// (Escaping the whole path first double-escapes `\` on Windows and produces a
// blockList that silently matches nothing.)
function escapePathForRegex(value) {
  return value
    .split(/[\\/]/)
    .map(segment => segment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('[\\\\/]');
}

const BLOCKED_DIRS = [
  'android', // CNG output — regenerated by `expo prebuild`, can be >1 GB
  'ios',
  'dist',
  'build',
  'coverage',
  '.git',
];

const blockedPatterns = [
  config.resolver.blockList,
  ...BLOCKED_DIRS.map(dir => new RegExp(`^${escapePathForRegex(path.join(projectRoot, dir))}[\\\\/].*`)),
].flat().filter(Boolean);

config.resolver.blockList = new RegExp(
  blockedPatterns.map(pattern => (pattern instanceof RegExp ? pattern.source : pattern)).join('|'),
);

// ── File watching ────────────────────────────────────────────────────────────
// Expo CLI defaults `useWatchman` to false, so without help Metro falls back to
// one `fs.watch` per directory and on Windows dies with
// "EMFILE: too many open files, watch" on a tree this size.
//   1. Watchman installed   → use it (fastest, recommended).
//   2. Windows, no Watchman → Metro's NativeWatcher: one recursive fs.watch per
//      root instead of one per directory. EPERM/EBUSY from files Windows is
//      still locking (pnpm installs, Gradle) are ignored instead of crashing.
// Force either path with EXPO_USE_WATCHMAN=1 / EXPO_USE_WATCHMAN=0.
function hasWatchman() {
  if (process.env.EXPO_USE_WATCHMAN === '1')
    return true;
  if (process.env.EXPO_USE_WATCHMAN === '0')
    return false;
  const probe = spawnSync('watchman', ['--version'], { stdio: 'ignore', shell: process.platform === 'win32' });
  return probe.status === 0;
}

config.resolver.useWatchman = hasWatchman();

if (!config.resolver.useWatchman && process.platform === 'win32') {
  try {
    const nativeWatcherPath = require.resolve('@expo/metro-file-map/build/watchers/NativeWatcher', {
      paths: [require.resolve('expo/metro-config')],
    });
    const NativeWatcher = require(nativeWatcherPath).default;
    if (typeof NativeWatcher?.isSupported === 'function' && typeof NativeWatcher.prototype.emitError === 'function') {
      NativeWatcher.isSupported = () => true;
      const emitError = NativeWatcher.prototype.emitError;
      NativeWatcher.prototype.emitError = function emitErrorUnlessLocked(error) {
        if (error?.code === 'EPERM' || error?.code === 'EBUSY')
          return;
        emitError.call(this, error);
      };
    }
  }
  catch {
    // Metro internals moved — keep the default watcher; install Watchman instead.
  }
}

// ── Tree shaking (production only, opt-in) ───────────────────────────────────
// Expo's tree shaking (experimental in SDK 58) drops unused exports in
// production bundles — e.g. the ~1,600 icons of lucide-react-native the app
// never imports. Enabled per build with EXPO_UNSTABLE_TREE_SHAKING=1 (set in
// the eas.json release profiles); it needs ESM import/export preserved, which
// experimentalImportSupport does. Dev builds are never affected.
if (process.env.EXPO_UNSTABLE_TREE_SHAKING === '1') {
  const getTransformOptions = config.transformer.getTransformOptions;
  config.transformer.getTransformOptions = async (...args) => {
    const base = getTransformOptions ? await getTransformOptions(...args) : {};
    return { ...base, transform: { ...base?.transform, experimentalImportSupport: true } };
  };
}

module.exports = withUniwindConfig(config, {
  cssEntryFile: './src/style/global.css',
  dtsFile: './uniwind-types.d.ts',
});
